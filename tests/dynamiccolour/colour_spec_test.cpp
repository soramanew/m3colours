void expectAllColours(const DynamicScheme& scheme, const std::vector<Argb>& expected) {
    const auto colours = material::allColours();
    ASSERT_EQ(colours.size(), expected.size());
    for (std::size_t i = 0; i < expected.size(); i++)
        EXPECT_EQ(colours[i]->getArgb(scheme), expected[i]) << colours[i]->name();
}

